#!/usr/bin/env python3
"""Generate the fixed, hash-verified built-in render lookup; offline authoring only.
Source pixels, manifests and readiness flags are never rewritten.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "crates/engine/src/cmd/render/library_data.rs"
CATALOGS = {
    "materials": "docs/render-materials/materials.json",
    "lighting": "docs/render-materials/lighting.json",
    "environments": "docs/render-materials/environments.json",
    "surfaces": "assets/render/starter/materials/source/recipes.json",
    "surface_manifest": "assets/render/starter/materials/manifest.json",
    "selene_appearances": "assets/render/selene/materials/appearance-pack.json",
    "selene_shots": "assets/render/selene/scenes/shots.json",
    "hdr": "assets/render/starter/environments/manifest.json",
    "rigs": "assets/render/starter/lighting/exports/rigs.json",
    "scenes": "docs/render-materials/scene-presets.json",
    "quality": "docs/render-materials/quality-presets.json",
    "capabilities": "docs/render-materials/capabilities.json",
}
ROLES = ("base_color", "normal_open_gl", "roughness", "metallic")


def load(relative: str) -> dict:
    value = json.loads((ROOT / relative).read_text(encoding="utf-8"))
    if not isinstance(value, dict) or not isinstance(value.get("items"), list):
        raise ValueError(f"Expected catalog with items: {relative}")
    return value


def checked_file(relative: str, expected: str) -> str:
    path = (ROOT / relative).resolve()
    path.relative_to(ROOT.resolve())
    if not path.is_file() or path.stat().st_size > 16 * 1024 * 1024:
        raise ValueError(f"Missing or excessive asset: {relative}")
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        raise ValueError(f"SHA-256 mismatch: {relative}: {actual}")
    return path.relative_to(ROOT).as_posix()


def generated() -> tuple[str, dict]:
    assets: dict[str, tuple[str, str]] = {}
    for item in load(CATALOGS["surface_manifest"])["items"]:
        for role in ROLES:
            spec = item["maps"][role]
            if spec["bit_depth"] != 8:
                raise ValueError(f"Not an eight-bit runtime channel: {item['id']}/{role}")
            key = f"{item['id']}/{role}"
            if key in assets:
                raise ValueError(f"Duplicate runtime resource: {key}")
            assets[key] = (checked_file(spec["path"], spec["sha256"]), spec["sha256"])
    maps = len(assets)
    for item in load(CATALOGS["hdr"])["items"]:
        relative = "assets/render/starter/environments/" + item["path"]
        if item["id"] in assets:
            raise ValueError(f"Duplicate HDR resource: {item['id']}")
        assets[item["id"]] = (checked_file(relative, item["sha256"]), item["sha256"])
    q = json.dumps
    text = [
        "//! Generated by tools/render-library/generate.py; do not edit by hand.",
        "//! Original source bytes and manifest digests remain unchanged.",
        "", "#[rustfmt::skip]",
        "pub(super) fn catalog(kind: &str) -> Option<&'static str> {",
        "    match kind {",
    ]
    for kind, relative in sorted(CATALOGS.items()):
        load(relative)
        text.append(f'        {q(kind)} => Some(include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../{relative}"))),')
    text += ["        _ => None,", "    }", "}", "", "#[rustfmt::skip]",
             "pub(super) fn asset(key: &str) -> Option<(&'static [u8], &'static str)> {",
             "    match key {"]
    for key, (relative, digest) in sorted(assets.items()):
        text.append(f'        {q(key)} => Some((include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../{relative}")), {q(digest)})),')
    text += ["        _ => None,", "    }", "}", ""]
    heights={}
    for item in load(CATALOGS["surface_manifest"])["items"]:
        record=item["maps"]["height"]
        path=checked_file(record["path"],record["sha256"])
        data=(ROOT/path).read_bytes()
        if record["bit_depth"]!=16 or data[:8]!=b"\x89PNG\r\n\x1a\n" or data[12:16]!=b"IHDR" or data[24:26]!=bytes([16,0]):
            raise ValueError("Height resource must remain original single-channel unsigned 16-bit PNG")
        heights[item["id"]]=(path,record["sha256"])
    text += ["", "#[rustfmt::skip]", "pub(super) fn height_asset(id: &str) -> Option<(&'static [u8], &'static str)> {", "    match id {"]
    for key,(relative,digest) in sorted(heights.items()):
        text.append(f'        {q(key)} => Some((include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../{relative}")), {q(digest)})),')
    text += ["        _ => None,", "    }", "}", ""]
    return "\n".join(text), {"embedded_heights":len(heights),"embedded_maps": maps, "embedded_hdr": len(assets)-maps,
                              "assets_checked": len(assets)+len(heights), "catalogs": len(CATALOGS),
                              "source_readiness_changed": False}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, summary = generated()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("Generated lookup is stale; run tools/render-library/generate.py")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(json.dumps(summary | {"status": "PASS", "mode": "check" if args.check else "generate"}))


if __name__ == "__main__":
    main()
